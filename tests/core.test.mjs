/* Выполняет код и возвращает сообщения; база восстанавливается, чтобы тесты не влияли друг на друга. */
function run(src) {
  const snap = JSON.stringify(C.getMeta());
  try {
    const x = C.execute(C.compile(src).code);
    return Array.from(x.out).filter((m) => m.k !== 'info').map((m) => (m.k === 'err' ? '! ' : '') + m.text.replace(/ /g, ' '));
  } finally {
    if (JSON.stringify(C.getMeta()) !== snap) C.setMeta(JSON.parse(snap));
  }
}
const say = (expr) => run('Сообщить(' + expr + ');').join(' | ');
function compileError(src) {
  try { C.compile(src); } catch (e) { assert.ok(e instanceof C.CompileError, 'ожидалась ошибка компиляции'); return e; }
  assert.fail('код скомпилировался, хотя не должен');
}

