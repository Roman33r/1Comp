/* строки табличного документа из снимка предпросмотра: «текст*» — жирный, «>» — выравнивание вправо */
function sheet(code) {
  const snap = JSON.stringify(C.getMeta());
  try {
    const x = C.execute(C.compile(code).code);
    return { out: Array.from(x.out).map((m) => m.text.replace(/ /g, ' ')), rows: Array.from(x.prints).map((pr) => Array.from(pr.segs[0].rows).map((r) => Array.from(r.cells).map((c) => c.x.replace(/ /g, ' ') + (c.b ? '*' : '') + (c.al === 'r' ? '>' : '')).join(' | '))) };
  } finally { if (JSON.stringify(C.getMeta()) !== snap) C.setMeta(JSON.parse(snap)); }
}

